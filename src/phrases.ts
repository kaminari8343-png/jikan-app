/**
 * しゃべるセリフは、ぜんぶこのファイルにあります。
 * 書きかえるだけで、アプリのしゃべり方が変わります。
 *
 * つかえる「穴うめ」:
 *   {name} … カードの名前（例: しゅくだい）
 *   {min}  … かかる分（例: じゅうごふん）  ※読み間違いがないよう、かなで読み上げます
 *   {next} … つぎのカードの名前
 *   {fixed} … じこくカードの名前（例: ゆうごはん）
 *   {time} … じこくカードの時刻の読み（例: ろくじ さんじゅっぷん）
 *
 * 設定画面の「テストさいせい」ボタンで、読み間違いがないか聞いて確かめられます。
 */
export const phrases = {
  /** カードがはじまるとき */
  start: '{name}、はじまるよー！{min}だよ',
  /** はんぶんたったとき */
  half: 'はんぶんたったよ。あと{min}だよ',
  /** のこり5分 */
  remaining5: 'あと{min}だよ',
  /** のこり1分 */
  remaining1: 'あと{min}だよ',
  /** カードの時間がおわったとき（このあと ask が続く） */
  end: '{name}、おわり！よくがんばったね',
  /** じぶんでふりかえる画面で、⭕️❌をえらんでもらうとき（スキップのときもこれ） */
  ask: '{name}、どうだった？じぶんでつけてみよう',
  /** ⭕️をえらんだとき（絵文字は読み間違えやすいので、ひらがなで書く） */
  rateGood: 'まるだね！',
  /** ❌をえらんだとき */
  rateBad: 'ばつだったね。つぎがんばろう',
  /** つぎのカードがあるとき（rateGood / rateBad のあとに続けて話す） */
  next: 'つぎは {next} だね',
  /** ぜんぶおわったとき */
  allDone: 'きょうのよてい ぜんぶおわったよ！すごいね！',
  /** じこくカードの時刻になったとき（いまのカードを止めて、ふりかえりへ） */
  fixedStart: '{time}だよ。{fixed}の じかんだよ',
  /** じこくカードの5分前 */
  fixedSoon: 'あと{min}で {fixed}だよ',
  /** じゆうじかんがはじまったとき */
  freeStart: 'じゆうじかんだよ。{fixed}まで あと{min}だよ',
  /** じかんぎれのカードがあったとき（ふりかえりのあとに話す） */
  timeoutNote: 'のこりの カードは じかんぎれだったよ',
  /** 「+5ふん」が、つぎのじこくカードをこえてしまうとき */
  cannotExtend: '{fixed}の じかんが あるから、のばせないよ',
  /** 1日のおわりのじこくカード（ねる）になったとき */
  endOfDay: 'おつかれさま。おやすみなさい',
  /** 「+5ふん」をおしたとき */
  extended: '{min}、のばしたよ',
}

export type PhraseKey = keyof typeof phrases

